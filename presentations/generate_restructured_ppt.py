def set_slide_bg(slide, color=LIGHT_BG):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def add_header(slide, section: str, title: str, page: str):
    bar = slide.shapes.add_shape(1, Inches(0), Inches(0), Inches(10), Inches(0.55))
    bar.fill.solid()
    bar.fill.fore_color.rgb = NAVY
    bar.line.fill.background()
    tf = bar.text_frame
    tf.text = f"杭州公司 · 专线特检经营复盘  |  {section}"
    for p in tf.paragraphs:
        p.font.size = Pt(11)
        p.font.color.rgb = WHITE
        p.font.bold = False

    box = slide.shapes.add_textbox(Inches(0.5), Inches(0.75), Inches(9), Inches(0.7))
    tf = box.text_frame
    tf.text = title
    for p in tf.paragraphs:
        p.font.size = Pt(26)
        p.font.bold = True
        p.font.color.rgb = NAVY

    pg = slide.shapes.add_textbox(Inches(9.2), Inches(7.1), Inches(0.6), Inches(0.3))
    pg.text_frame.text = page
    pg.text_frame.paragraphs[0].font.size = Pt(10)
    pg.text_frame.paragraphs[0].font.color.rgb = GRAY
    pg.text_frame.paragraphs[0].alignment = PP_ALIGN.RIGHT


def add_bullets(slide, items, left=0.5, top=1.6, width=9, height=5.2, size=14):
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = item
        p.font.size = Pt(size)
        p.font.color.rgb = GRAY
        p.space_after = Pt(8)
        p.level = 0


